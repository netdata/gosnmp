// The characterization tests pin the observable behavior of the public entry
// points, known bugs included, in golden files under testdata/codec (encode
// and decode) and testdata/usm (SNMPv3 security). Each golden file is a list
// of cases:
//
//	== <case name>
//	<dump line>
//	...
//
// The results are the same on every platform, so one golden file serves both
// word sizes; a case whose input a 32-bit int or uint cannot hold runs on
// 64-bit platforms only (goldenCase.wide). Regenerate on a 64-bit platform
// with -update, and check on a 32-bit one, for example:
//
//	go test -run 'Characterization' -update .
//	GOARCH=386 go test -run 'Characterization' .   (on linux/amd64)

var updateGolden = flag.Bool("update", false, "rewrite the characterization golden files in testdata")

// goldenFiles is a directory of characterization golden files.
type goldenFiles struct {
	dir   string
	title string // the header names the results "<title> characterization results"
}

var (
	codecGolden = goldenFiles{dir: "testdata/codec", title: "Codec"}
	usmGolden   = goldenFiles{dir: "testdata/usm", title: "USM"}
)

// goldenCase is one named result of a characterization test.
type goldenCase struct {
	name string
	dump string
	// wide marks a case whose input a 32-bit int or uint cannot hold: 32-bit
	// platforms do not run it, and the golden file holds its 64-bit result.
	wide bool
}

// skipped reports whether c does not run on this platform (see wide).
func (c goldenCase) skipped() bool {
	return c.wide && strconv.IntSize == 32
}

// goldenSection is one parsed golden file entry.
type goldenSection struct {
	name string
	dump string
}

// check compares cases with <dir>/<file>.golden, or rewrites the golden file
// when -update is set.
func (g goldenFiles) check(t *testing.T, file string, cases []goldenCase) {
	t.Helper()

	seen := make(map[string]bool, len(cases))
	for _, c := range cases {
		if seen[c.name] {
			t.Fatalf("duplicate characterization case %q", c.name)
		}
		seen[c.name] = true
	}

	basePath := filepath.Join(g.dir, file+".golden")

	if *updateGolden {
		g.update(t, file, basePath, cases)
		return
	}

	want, err := readGoldenMap(basePath)
	if err != nil {
		t.Fatalf("%v (regenerate with -update)", err)
	}

	for _, c := range cases {
		if c.skipped() {
			continue
		}
		wantDump, ok := want[c.name]
		if !ok {
			t.Errorf("case %q is missing from %s (regenerate with -update)", c.name, basePath)
			continue
		}
		if wantDump != c.dump {
			assert.Equal(t, wantDump, c.dump, "case %q differs from %s", c.name, basePath)
		}
	}
	for name := range want {
		if !seen[name] {
			t.Errorf("%s: case %q no longer exists (regenerate with -update)", basePath, name)
		}
	}
}

// update rewrites the golden file with cases. On a 32-bit platform, which
// does not run the wide cases, it refuses rather than drop them.
func (g goldenFiles) update(t *testing.T, file, basePath string, cases []goldenCase) {
	t.Helper()

	for _, c := range cases {
		if c.skipped() {
			t.Fatalf("case %q runs on 64-bit platforms only: regenerate %s on one", c.name, basePath)
		}
	}
	header := fmt.Sprintf("# %s characterization results (%s). Generated by go test -update; do not edit.\n", g.title, file)
	writeGoldenFile(t, basePath, header, cases)
}

func writeGoldenFile(t *testing.T, path, header string, cases []goldenCase) {
	t.Helper()

	var buf bytes.Buffer
	buf.WriteString(header)
	for _, c := range cases {
		fmt.Fprintf(&buf, "\n== %s\n%s\n", c.name, c.dump)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, buf.Bytes(), 0o644); err != nil {
		t.Fatal(err)
	}
	t.Logf("wrote %s (%d cases)", path, len(cases))
}

func readGoldenMap(path string) (map[string]string, error) {
	sections, err := readGoldenFile(path)
	if err != nil {
		return nil, err
	}
	m := make(map[string]string, len(sections))
	for _, s := range sections {
		if _, ok := m[s.name]; ok {
			return nil, fmt.Errorf("%s: duplicate case %q", path, s.name)
		}
		m[s.name] = s.dump
	}
	return m, nil
}

func readGoldenFile(path string) ([]goldenSection, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}

	var sections []goldenSection
	var lines []string
	flush := func() {
		if len(sections) == 0 {
			return
		}
		for len(lines) > 0 && lines[len(lines)-1] == "" {
			lines = lines[:len(lines)-1]
		}
		sections[len(sections)-1].dump = strings.Join(lines, "\n")
		lines = nil
	}

	sc := bufio.NewScanner(bytes.NewReader(data))
	sc.Buffer(nil, 1<<20)
	for sc.Scan() {
		line := sc.Text()
		switch {
		case strings.HasPrefix(line, "== "):
			flush()
			sections = append(sections, goldenSection{name: strings.TrimPrefix(line, "== ")})
		case len(sections) == 0:
			if line != "" && !strings.HasPrefix(line, "#") {
				return nil, fmt.Errorf("%s: unexpected line before the first case: %q", path, line)
			}
		default:
			lines = append(lines, line)
		}
	}
	if err := sc.Err(); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	flush()
	return sections, nil
}

// codecSentinels are the exported errors a codec result is matched against.
var codecSentinels = []struct {
	name string
	err  error
}{
	{"ErrBase128IntegerTooLarge", ErrBase128IntegerTooLarge},
	{"ErrBase128IntegerTruncated", ErrBase128IntegerTruncated},
	{"ErrFloatBufferTooShort", ErrFloatBufferTooShort},
	{"ErrFloatTooLarge", ErrFloatTooLarge},
	{"ErrIntegerTooLarge", ErrIntegerTooLarge},
	{"ErrInvalidOidLength", ErrInvalidOidLength},
	{"ErrInvalidPacketLength", ErrInvalidPacketLength},
	{"ErrZeroByteBuffer", ErrZeroByteBuffer},
	{"ErrZeroLenInteger", ErrZeroLenInteger},
	{"ErrDecryption", ErrDecryption},
	{"ErrInvalidMsgs", ErrInvalidMsgs},
	{"ErrNotInTimeWindow", ErrNotInTimeWindow},
	{"ErrUnknownEngineID", ErrUnknownEngineID},
	{"ErrUnknownPDUHandlers", ErrUnknownPDUHandlers},
	{"ErrUnknownReportPDU", ErrUnknownReportPDU},
	{"ErrUnknownSecurityLevel", ErrUnknownSecurityLevel},
	{"ErrUnknownSecurityModels", ErrUnknownSecurityModels},
	{"ErrUnknownUsername", ErrUnknownUsername},
	{"ErrWrongDigest", ErrWrongDigest},
}

// dumpError describes an error by the exported sentinels it matches; the
// message text is not part of the pinned behavior.
func dumpError(err error) string {
	var matched []string
	for _, s := range codecSentinels {
		if errors.Is(err, s.err) {
			matched = append(matched, s.name)
		}
	}
	if len(matched) == 0 {
		return "error"
	}
	return "error (" + strings.Join(matched, ", ") + ")"
}

// observe runs fn and reports whether it panicked and whether it wrote to
// os.Stdout, which the library does when it recovers from some panics. It
// swaps the global os.Stdout, so tests that use it must not run in parallel
// with others.
func observe(fn func()) (panicked, wroteStdout bool) {
	r, w, err := os.Pipe()
	if err != nil {
		panic(err)
	}
	written := make(chan int64)
	go func() {
		n, _ := io.Copy(io.Discard, r)
		_ = r.Close()
		written <- n
	}()

	stdout := os.Stdout
	os.Stdout = w
	func() {
		defer func() {
			if recover() != nil {
				panicked = true
			}
		}()
		fn()
	}()
	os.Stdout = stdout
	_ = w.Close()

	return panicked, <-written > 0
}

// dumpBytesLimit is the length above which dumpBytes abbreviates its output.
const dumpBytesLimit = 1024

// dumpBytes prints a byte slice in hex, telling nil and empty apart. Long
// slices are pinned by their first bytes, length and SHA-256.
func dumpBytes(b []byte) string {
	switch {
	case b == nil:
		return "nil"
	case len(b) == 0:
		return "empty"
	case len(b) > dumpBytesLimit:
		return fmt.Sprintf("%x... (%d bytes, sha256 %x)", b[:64], len(b), sha256.Sum256(b))
	default:
		return fmt.Sprintf("%x", b)
	}
}
